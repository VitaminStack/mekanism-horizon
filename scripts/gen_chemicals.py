"""Generate the native mod's fluid and chemical table (M06) from a Mekanism 26.3 checkout:
`native/mekanism_native/api/src/chemicals_table.rs`.

Sources (upstream, pinned commit in TODO.md):
- fluids: `MekanismFluids` (registration order; tint from the matching chemical for liquid
  chemicals, else from the registration), names `block.mekanism.<id>` from en_us;
- chemicals: the datapack registry `data/mekanism/mekanism/chemical/*.json` and Mekanism Generators'
  `data/mekanismgenerators/mekanism/chemical/*.json` (26.3 makes chemicals
  datapack entries), tint from `tint` (or `color_representation` for infuse types), pigments from
  `EnumColor`'s RGB, names `chemical.mekanism.<id>` from en_us.

Horizon has only vanilla world fluids and no chemical registry, so both live in block-entity
tanks as fluid ids (see docs/CHEMISTRY.md): fluids as `mekanism:<id>`, chemicals as
`mekanism:chemical/<id>`, which keeps a chemical and the liquid of the same name apart.

Run: `python -I scripts/gen_chemicals.py <Mekanism checkout>`.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'native/mekanism_native/api/src/chemicals_table.rs'

def pigment_rgb(up):
    """Pigment colour by registry prefix (`blue`, `dark_red`), from Mekanism's `EnumColor`."""
    src = (up / 'src/api/java/mekanism/api/text/EnumColor.java').read_text(encoding='utf-8')
    out = {}
    for m in re.finditer(r'^\s+[A-Z_]+\((?:DyeColor\.([A-Z_]+)|"([a-z_]+)"), "[^"]+", 0x([0-9A-Fa-f]{6})', src, re.M):
        out[(m.group(1) or m.group(2)).lower()] = int(m.group(3), 16)
    return out


def argb(hex_text):
    return int(hex_text.lstrip('#'), 16) & 0xFFFFFFFF


def main(up):
    gen = up / 'src/datagen/generated/mekanism'
    lang = json.loads((gen / 'assets/mekanism/lang/en_us.json').read_text(encoding='utf-8'))
    chem_dir = gen / 'data/mekanism/mekanism/chemical'

    rgb = pigment_rgb(up)
    chemicals = []
    for f in sorted(chem_dir.glob('*.json')):
        if f.stem == 'empty':
            continue
        data = json.loads(f.read_text(encoding='utf-8'))
        if data.get('type') == 'mekanism:enum_color_pigment':
            color = 0xFF000000 | rgb[data['color']]
        else:
            # A white tint draws an untinted icon texture; take a light grey for the gauge.
            color = argb(data.get('color_representation') or data.get('tint', '#ffffffff'))
            if color == 0xFFFFFFFF:
                color = 0xFFC8C8C8
        name = lang.get(f'chemical.mekanism.{f.stem}', f.stem.replace('_', ' ').title())
        chemicals.append((f.stem, name, color))
    # Mekanism Generators' chemicals (deuterium, tritium, D-T fuel) come last, so the menu indices of the
    # ones before stay put. Recipes name them `mekanismgenerators:<id>`; the tank id is `mekanism:chemical/<id>`.
    gen_root = up / 'src/datagen/generated/mekanismgenerators'
    gen_lang = json.loads((gen_root / 'assets/mekanismgenerators/lang/en_us.json').read_text(encoding='utf-8'))
    for f in sorted((gen_root / 'data/mekanismgenerators/mekanism/chemical').glob('*.json')):
        data = json.loads(f.read_text(encoding='utf-8'))
        name = gen_lang.get(f'chemical.mekanismgenerators.{f.stem}', f.stem.replace('_', ' ').title())
        chemicals.append((f.stem, name, argb(data.get('color_representation') or data['tint'])))
    tint = {c[0]: c[2] for c in chemicals}

    src = (up / 'src/main/java/mekanism/common/registries/MekanismFluids.java').read_text(encoding='utf-8')
    fluids = []
    for m in re.finditer(r'FLUIDS\.(registerLiquidChemical\(ChemicalConstants\.(\w+)\)|register\("(\w+)"(.*?)\);)',
                         src, re.S):
        if m.group(2):
            id_ = m.group(2).lower()
            color = tint[id_]
        else:
            id_ = m.group(3)
            t = re.search(r'tint\(0x([0-9A-Fa-f]{8})\)', m.group(4))
            color = int(t.group(1), 16) if t else 0xFFC8C8C8
        fluids.append((id_, lang.get(f'block.mekanism.{id_}', id_), color))

    def rows(entries):
        return '\n'.join(f'    ("{i}", "{n}", 0x{c:08X}),' for i, n, c in entries)

    OUT.write_text(f'''// Generated by scripts/gen_chemicals.py from Mekanism 26.3; do not edit.

/// Mekanism's fluids (`MekanismFluids`): id path, English name, tint.
pub const FLUIDS: [(&str, &str, u32); {len(fluids)}] = [
{rows(fluids)}
];

/// Mekanism's chemicals (`data/mekanism/mekanism/chemical`): id path, English name, tint.
pub const CHEMICALS: [(&str, &str, u32); {len(chemicals)}] = [
{rows(chemicals)}
];
''', encoding='utf-8')
    print(f'{len(fluids)} fluids, {len(chemicals)} chemicals -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main(Path(sys.argv[1]))
