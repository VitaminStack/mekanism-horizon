"""Offline structural sanity checks; does NOT replace official cargo horizon-mod check."""
from pathlib import Path
import json
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / 'content' / 'mekanism'


def main():
    manifest = tomllib.loads((CONTENT / 'horizon-mod.toml').read_text(encoding='utf-8'))
    assert manifest['id'] == 'mekanism'
    assert manifest['api'] == '0.2'
    assert manifest['side'] == 'both'
    assert 'registries' in manifest['capabilities']
    assert not (CONTENT / 'Cargo.toml').exists(), 'Content mods must not have Cargo.toml in their root'
    json_files = sorted(CONTENT.rglob('*.json'))
    for path in json_files:
        json.loads(path.read_text(encoding='utf-8'))
    assert len(json_files) >= 10, 'Expected item, block, model, loot, recipe and language files'
    item = json.loads((CONTENT/'data/mekanism/horizon/item/ingot_osmium.json').read_text(encoding='utf-8'))
    block = json.loads((CONTENT/'data/mekanism/horizon/block/block_osmium.json').read_text(encoding='utf-8'))
    assert item['template'].startswith('minecraft:')
    assert block['template'].startswith('minecraft:')
    for name in ['ingot_osmium', 'block_osmium', 'basic_energy_cube']:
        assert (CONTENT/f'assets/mekanism/items/{name}.json').exists(), f'Missing item model: {name}'
    cube = json.loads((CONTENT/'data/mekanism/horizon/block/basic_energy_cube.json').read_text(encoding='utf-8'))
    assert cube['item'] is True
    assert cube['template'] == 'minecraft:barrel', 'Energy cubes need a menu-opening template'
    assert 'facing' not in cube['state_properties'], 'Barrel already defines facing'
    menu = json.loads((CONTENT/'data/mekanism/horizon/menu/energy_cube.json').read_text(encoding='utf-8'))
    assert menu == {'slots': 1, 'data_slots': 11, 'results': [0]}
    for tier in ['basic', 'advanced', 'elite', 'ultimate', 'creative']:
        tier_data = json.loads((CONTENT/f'data/mekanism/horizon/block/{tier}_energy_cube.json').read_text(encoding='utf-8'))
        assert tier_data['template'] == 'minecraft:barrel'
        assert 'facing' not in tier_data['state_properties']
    for rel in ['assets/mekanism/blockstates/basic_energy_cube.json',
                'assets/mekanism/models/block/basic_energy_cube.json',
                'data/mekanism/loot_table/blocks/basic_energy_cube.json',
                'data/mekanism/recipe/energy_cube/basic.json']:
        assert (CONTENT/rel).is_file(), f'Missing Energy Cube file: {rel}'
    # Cube needs any pickaxe (no tool tier), like Mekanism machines.
    rel = 'data/minecraft/tags/block/mineable/pickaxe.json'
    assert 'mekanism:basic_energy_cube' in json.loads((CONTENT/rel).read_text(encoding='utf-8'))['values']

    # Generators (M04): upstream's own mod, so its own content mod with upstream ids.
    gen = ROOT / 'content' / 'mekanismgenerators'
    manifest = tomllib.loads((gen / 'horizon-mod.toml').read_text(encoding='utf-8'))
    assert manifest['id'] == 'mekanismgenerators' and manifest['api'] == '0.2'
    assert 'registries' in manifest['capabilities']
    gen_files = sorted(gen.rglob('*.json'))
    for path in gen_files:
        json.loads(path.read_text(encoding='utf-8'))
    for name in ['heat_generator', 'solar_generator']:
        decl = json.loads((gen/f'data/mekanismgenerators/horizon/block/{name}.json').read_text(encoding='utf-8'))
        assert decl['template'] == 'minecraft:barrel', 'Generators need a menu-opening template'
        assert (gen/f'data/mekanismgenerators/horizon/menu/{name}.json').is_file()
        assert (gen/f'assets/mekanismgenerators/blockstates/{name}.json').is_file()
        assert (gen/f'data/mekanismgenerators/loot_table/blocks/{name}.json').is_file()
    json_files += gen_files
    # Additions (M12): generated by scripts/gen_additions.py (plastic blocks, glow panels, Obsidian TNT).
    adds = ROOT / 'content' / 'mekanismadditions'
    manifest = tomllib.loads((adds / 'horizon-mod.toml').read_text(encoding='utf-8'))
    assert manifest['id'] == 'mekanismadditions' and manifest['api'] == '0.2'
    add_files = sorted(adds.rglob('*.json'))
    for path in add_files:
        json.loads(path.read_text(encoding='utf-8'))
    decls = sorted((adds / 'data/mekanismadditions/horizon/block').glob('*.json'))
    assert len(decls) == 271, f'Expected 271 additions blocks, found {len(decls)}'
    for decl in decls:
        n = decl.stem
        assert json.loads(decl.read_text(encoding='utf-8'))['template'].startswith('minecraft:')
        for rel in (f'assets/mekanismadditions/blockstates/{n}.json', f'assets/mekanismadditions/items/{n}.json',
                    f'data/mekanismadditions/loot_table/blocks/{n}.json'):
            assert (adds / rel).is_file(), f'Missing additions file: {rel}'
    json_files += add_files
    print(f'OK: {len(json_files)} JSON-Dateien + Manifeste geprueft (nur Strukturtest).')
    print(r'Fuer offizielle Pruefung: .\scripts\Build-Content.ps1')


if __name__ == '__main__':
    try:
        main()
    except Exception as exc:
        print(f'FEHLER: {exc}', file=sys.stderr)
        sys.exit(1)
