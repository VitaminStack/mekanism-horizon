"""List every block and item tag the content mods define, for the Dictionary (M11).

Horizon offers no call that lists the tags of a block or item, only a membership test per
tag (`block_name_in_tag`, `server_item_in_tag`). The Dictionary therefore tests this list.
Writes `native/mekanism_native/api/src/dictionary_tags.rs`. Run after `import_upstream.py`:
`python scripts/gen_dictionary_tags.py`.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'native/mekanism_native/api/src/dictionary_tags.rs'
# Vanilla tags players know; the content mods only define their own and the convention tags.
VANILLA = {
    'block': ['minecraft:logs', 'minecraft:planks', 'minecraft:leaves', 'minecraft:sand', 'minecraft:dirt',
              'minecraft:base_stone_overworld', 'minecraft:mineable/pickaxe', 'minecraft:mineable/axe',
              'minecraft:mineable/shovel', 'minecraft:mineable/hoe', 'minecraft:needs_iron_tool',
              'minecraft:needs_diamond_tool', 'minecraft:needs_stone_tool'],
    'item': ['minecraft:logs', 'minecraft:planks', 'minecraft:coals', 'minecraft:swords',
             'minecraft:pickaxes', 'minecraft:axes', 'minecraft:shovels', 'minecraft:hoes'],
}


def collect(kind):
    tags = set(VANILLA[kind])
    for tag_file in (ROOT / 'content').glob(f'*/data/*/tags/{kind}/**/*.json'):
        parts = tag_file.relative_to(ROOT / 'content').parts
        ns = parts[2]
        rel = '/'.join(parts[4 + 1:]).removesuffix('.json')
        tags.add(f'{ns}:{rel}')
    return sorted(tags)


lines = ['// Generated by scripts/gen_dictionary_tags.py; do not edit.', '']
for kind in ('block', 'item'):
    tags = collect(kind)
    lines.append(f'pub const {kind.upper()}_TAGS: [&str; {len(tags)}] = [')
    lines += [f'    "{t}",' for t in tags]
    lines += ['];', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print(f'{OUT.name}: {len(collect("block"))} block tags, {len(collect("item"))} item tags')
