"""List the item tags the Oredictionificator can filter by, with their members (M08).

Horizon offers a native mod only a membership test per tag (`server_item_in_tag`), no call that
lists a tag's items, and a screen cannot test tags at all. The Oredictionificator therefore reads
this table: every item tag of the content mods whose path starts with one of Mekanism's
`validOredictionificatorFilters` prefixes (`GeneralConfig`: `c:` + `ingots/`, `ores/`, `dusts/`,
`nuggets/`, `storage_blocks/`, `raw_materials/`), with `#tag` references resolved and the members
in file order (the first is the default output, as `filterTag.get(0)` upstream).
Writes `native/mekanism_native/api/src/oredict_tags.rs`. Run after `import_upstream.py`:
`python scripts/gen_oredict_tags.py`.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'native/mekanism_native/api/src/oredict_tags.rs'
NAMESPACE = 'c'
PREFIXES = ['ingots/', 'ores/', 'dusts/', 'nuggets/', 'storage_blocks/', 'raw_materials/']


def load():
    """Every item tag of the content mods as `path -> values` (the mods' files merged, in mod order)."""
    tags = {}
    for mod in sorted((ROOT / 'content').iterdir()):
        base = mod / 'data' / NAMESPACE / 'tags' / 'item'
        for f in sorted(base.rglob('*.json')) if base.is_dir() else []:
            path = f.relative_to(base).with_suffix('').as_posix()
            values = json.loads(f.read_text(encoding='utf-8')).get('values', [])
            tags.setdefault(path, []).extend(v for v in values if isinstance(v, str))
    return tags


def members(tags, path, seen=()):
    out = []
    for v in tags.get(path, []):
        if v.startswith(f'#{NAMESPACE}:'):
            if v[3:] not in seen:
                out += members(tags, v[3:], seen + (path,))
        elif not v.startswith('#') and v not in out:
            out.append(v)
    return list(dict.fromkeys(out))


tags = load()
table = {f'{NAMESPACE}:{p}': members(tags, p) for p in sorted(tags) if p.startswith(tuple(PREFIXES))}
table = {t: m for t, m in table.items() if m}
lines = ['// Generated by scripts/gen_oredict_tags.py; do not edit.', '',
         f'pub const TAGS: [(&str, &[&str]); {len(table)}] = [']
for tag, items in table.items():
    lines.append(f'    ("{tag}", &[{", ".join(json.dumps(i) for i in items)}]),')
lines += ['];', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
multi = sum(len(m) > 1 for m in table.values())
print(f'{OUT.name}: {len(table)} tags, {multi} with several items')
